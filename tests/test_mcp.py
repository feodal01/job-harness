import json

import pytest
from mcp.server.fastmcp.exceptions import ToolError

from src.mcp.server import create_mcp
from src.runtime.manager import ServiceError
from src.schemas.service import ServiceStatus


class ManagerProbe:
    def __init__(self) -> None:
        self.calls = []
        self.failure = None
        self.response = {"id": "persisted", "status": "queued"}

    async def status(self):
        self.calls.append(("status",))
        return ServiceStatus(version="0.1.0", status="stopped")

    async def start(self):
        self.calls.append(("start",))
        return ServiceStatus(version="0.1.0", status="running")

    async def stop(self, cancel_active=False):
        self.calls.append(("stop", cancel_active))
        return ServiceStatus(version="0.1.0", status="stopped")

    async def request(self, method, path, **kwargs):
        self.calls.append((method, path, kwargs))
        if self.failure:
            raise self.failure
        return self.response


async def test_tools_expose_typed_brief_and_filters_and_safe_status() -> None:
    manager = ManagerProbe()
    server = create_mcp(manager)
    tools = {tool.name: tool for tool in await server.list_tools()}
    assert {
        "create_brief",
        "start_search",
        "get_results",
        "stop_service",
        "get_service_status",
    } <= tools.keys()
    schema = tools["create_brief"].inputSchema
    assert tools["create_brief"].outputSchema is not None
    assert "filters" in schema["$defs"]["BriefInput"]["properties"]
    assert tools["stop_service"].annotations.destructiveHint
    await server.call_tool("get_service_status", {})
    assert manager.calls == [("status",)]
    await server.call_tool("stop_service", {})
    assert manager.calls[-1] == ("stop", False)


async def test_invalid_brief_never_reaches_api_and_errors_are_reported() -> None:
    manager = ManagerProbe()
    server = create_mcp(manager)
    with pytest.raises(ToolError):
        await server.call_tool("create_brief", {"brief": {"name": "", "queries": [" "]}})
    with pytest.raises(ToolError):
        await server.call_tool("get_run", {"run_id": "../../service/stop"})
    assert manager.calls == []
    manager.failure = ServiceError("HTTP 409: active search")
    with pytest.raises(ToolError, match="active search"):
        await server.call_tool(
            "start_search",
            {"search": {"brief_id": "one", "source_rules": {"mode": "selected", "include": ["hh_ru"]}}},
        )
    assert manager.calls[-1][:2] == ("POST", "/api/v1/runs")


async def test_brief_and_search_contract_reaches_existing_api() -> None:
    manager = ManagerProbe()
    server = create_mcp(manager)
    result = await server.call_tool("create_brief", {"brief": {"name": "Python", "queries": ["python"]}})
    assert "persisted" in str(result)
    assert manager.calls[-1][2]["body"]["queries"] == ["python"]
    await server.call_tool("get_results", {"run_id": "one", "page": 2, "page_size": 5})
    assert manager.calls[-1] == (
        "GET",
        "/api/v1/runs/one/results",
        {
            "params": {
                "page": 2,
                "page_size": 5,
                "selection": "all",
            }
        },
    )
    # Tool output is serializable, including the structured content generated by the SDK.
    json.dumps(result, default=lambda value: value.model_dump())


async def test_authorize_has_no_provider_or_credentials_and_catalog_is_typed() -> None:
    manager = ManagerProbe()
    server = create_mcp(manager)
    tools = {tool.name: tool for tool in await server.list_tools()}
    assert tools["authorize"].inputSchema["properties"] == {}
    assert tools["list_companies"].annotations.readOnlyHint
    assert tools["list_companies"].outputSchema["properties"]["items"]["type"] == "array"
    manager.response = {"authenticated": False, "user": None, "login_url": "http://127.0.0.1:8765/auth"}
    result = await server.call_tool("authorize", {})
    assert "http://127.0.0.1:8765/auth" in str(result)
    assert manager.calls[-1][:2] == ("POST", "/api/v1/auth/authorize")
    manager.response = {"items": [], "total": 0, "page": 2, "page_size": 5}
    await server.call_tool("list_companies", {"category": "Финтех", "page": 2, "page_size": 5})
    assert manager.calls[-1] == (
        "GET",
        "/api/v1/companies",
        {"params": {"category": "Финтех", "page": 2, "page_size": 5}},
    )
    before = len(manager.calls)
    with pytest.raises(ToolError):
        await server.call_tool("list_companies", {"page_size": 10000})
    assert len(manager.calls) == before
    manager.failure = ServiceError("HTTP 401: Войдите: http://127.0.0.1:8765/auth")
    with pytest.raises(ToolError, match="/auth"):
        await server.call_tool("list_companies", {})


async def test_agent_can_discover_filter_values_from_tool_schema_and_call_lookup() -> None:
    manager = ManagerProbe()
    server = create_mcp(manager)
    tools = {tool.name: tool for tool in await server.list_tools()}
    company_tool = tools["list_companies"]
    assert "get_company_filters" in company_tool.description
    for field in ("category", "specialization"):
        assert "get_company_filters" in company_tool.inputSchema["properties"][field]["description"]
    lookup = tools["get_company_filters"]
    assert lookup.inputSchema["properties"]["field"]["enum"] == ["category", "specialization"]
    assert lookup.annotations.readOnlyHint
    manager.response = {
        "field": "specialization",
        "items": [{"value": "CRM и продажи", "link_count": 4}],
        "page": 1,
        "page_size": 50,
        "total": 1,
    }
    result = await server.call_tool(
        "get_company_filters", {"field": "specialization", "category": "Корпоративное ПО", "query": "CRM"}
    )
    assert "CRM и продажи" in str(result)
    assert manager.calls == [
        (
            "GET",
            "/api/v1/companies/filters",
            {
                "params": {
                    "field": "specialization",
                    "category": "Корпоративное ПО",
                    "query": "CRM",
                    "page": 1,
                    "page_size": 50,
                }
            },
        )
    ]
    with pytest.raises(ToolError):
        await server.call_tool("get_company_filters", {"field": "unknown"})
    assert len(manager.calls) == 1
